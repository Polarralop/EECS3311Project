    s = Seq(["User", GUI, CTRL, AGENT, R, T, S, P, B])
    s.call(AGENT, R, "execute(call, session)")
    s.note(AGENT, "inside runToolLoop during a turn (SD05)")
    s.call(R, T, "execute(args, session)")
    s.frame("alt", "[the title is already lore or already waiting]")
    s.ret(T, R, "ToolResult.error(reason)")
    s.orelse()
    s.call(T, S, "addProposal(proposal)").ret(S, T)
    s.ret(T, R, "ToolResult.ok(\"P1 is waiting\")")
    s.end()
    s.ret(R, AGENT, "ToolResult")
    s.done(AGENT)
    s.note(CTRL, "after the turn (SD04)")
    s.call(CTRL, S, "notifyObservers()").call(S, GUI, "onStoryChanged(session)")
    s.self_(GUI, "refreshProposals(session)")
    s.ret(GUI, S).ret(S, CTRL)
    s.done(CTRL)
    s.call("User", GUI, "Approve or Reject")
    s.self_(GUI, "resolveSelected(approved)")
    s.call(GUI, CTRL, "resolveProposal(id, approved)")
    s.frame("alt", "[approved]")
    s.call(CTRL, S, "approveProposal(id)")
    s.call(S, P, "approve()").ret(P, S, "LoreEntry")
    s.call(S, B, "add(entry)").ret(B, S)
