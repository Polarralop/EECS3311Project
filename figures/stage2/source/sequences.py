from umlgen import Seq

GUI, CTRL, AGENT = ":StoryGUI", ":StoryController", ":StoryAgent"


def notify(s, ctrl=CTRL, sess=":StorySession", gui=GUI):
    s.call(ctrl, sess, "notifyObservers()").call(sess, gui, "onStoryChanged(session)")
    s.ret(gui, sess).ret(sess, ctrl)


