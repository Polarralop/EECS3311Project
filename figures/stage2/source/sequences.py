    s.call(E, S, "lastTurn()").ret(S, E, "Turn")
    s.self_(E, "setNarration(text), setWarnings([])")
    s.ret(E, H).ret(H, CTRL)
    notify(s, sess=S)
    s.ret(CTRL, GUI)
    s.end()
    s.end()
