    s.call(GUI, CTRL, "undoTurn()")
    s.call(CTRL, H, "undoLast()")
    s.call(H, C, "undo()")
    s.call(C, S, "removeLastTurn()").ret(S, C, "Turn")
    s.call(C, S, "setPlot(plotBefore)").ret(S, C)
    s.ret(C, H)
    s.note(H, "last command an edit: EditTurnCommand.undo() restores oldNarration and oldWarnings")
    s.ret(H, CTRL)
    notify(s, sess=S)
    s.ret(CTRL, GUI)
    s.orelse("[Retry]")
    s.call("User", GUI, "Retry")
    s.call(GUI, CTRL, "retryTurn()")
    s.call(CTRL, H, "latest(SubmitTurnCommand)").ret(H, CTRL, "command")
    s.frame("loop", "[an edit of that turn is on top]")
    s.call(CTRL, H, "undoLast()").ret(H, CTRL)
    s.end()
    s.call(CTRL, H, "undoLast()").ret(H, CTRL)
    s.note(CTRL, "the turn is removed and the plot restored, as for Undo")
    s.call(CTRL, C, "getInput(), getMode()").ret(C, CTRL, "input, mode")
    s.call(CTRL, H, "run(new SubmitTurnCommand(...))")
    s.note(H, "as SD04 from execute()")
    s.frame("alt", "[the new attempt fails]")
    s.ret(H, CTRL, "LLMException")
    notify(s, sess=S)
    s.ret(CTRL, GUI, "LLMException")
    s.self_(GUI, "showError(message); input put back")
    s.orelse()
    s.ret(H, CTRL)
    notify(s, sess=S)
    s.ret(CTRL, GUI, "Turn")
    s.end()
    s.orelse("[Edit]")
    s.call("User", GUI, "Edit")
